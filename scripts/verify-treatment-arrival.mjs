import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';

const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://localhost:3000', { waitUntil: 'networkidle' });
  await page.waitForTimeout(1400);
  await page.mouse.move(720, 450);
  await page.mouse.wheel(0, 120);
  await page.waitForTimeout(1100);
  assert.ok(await page.evaluate(() => scrollY < 500), 'Wheel outside transition must keep native scrolling');
  await page.evaluate(() => window.scrollTo({ top: 2500, behavior: 'instant' }));
  await page.waitForTimeout(1300);
  assert.equal(await page.locator('.treatment-word').first().evaluate(el => getComputedStyle(el).visibility), 'hidden');
  await page.mouse.wheel(0, 120);
  await page.waitForTimeout(800);
  assert.ok(await page.evaluate(() => scrollY >= 2600 && scrollY < 2700), 'Wheel must stay native without pulling section to top');
  const alpha = () => page.locator('.treatment-features .treatment-reveal').first().evaluate(el => Number(getComputedStyle(el).opacity));
  await page.evaluate(() => window.scrollTo({ top: 3000, behavior: 'instant' }));
  await page.waitForTimeout(1000);
  assert.equal(await alpha(), 0, 'Background must rise first before cards enter');
  assert.equal(await page.locator('.treatment-word').first().evaluate(el => Number(getComputedStyle(el).opacity)), 0, 'Text must wait until section reaches 65% of viewport');
  await page.evaluate(() => window.scrollTo({ top: 3150, behavior: 'instant' }));
  await page.waitForTimeout(1000);
  const early = await alpha();
  assert.ok(early > 0 && early < 0.7, `Cards must enter progressively, early opacity=${early}`);
  assert.ok(Number(await page.locator('.treatment-word').first().evaluate(el => getComputedStyle(el).opacity)) > early, 'Title must lead cards');
  await page.screenshot({ path: 'artifacts/treatment-fluid-early.png' });
  await page.waitForTimeout(800);
  assert.ok(Math.abs(await alpha() - early) < 0.02, 'Animation must stay at scroll position after smoothing settles');
  assert.ok(Math.abs(await page.evaluate(() => scrollY) - 3150) < 2, 'Idle transition must not move page');
  await page.evaluate(() => window.scrollTo({ top: 3400, behavior: 'instant' }));
  await page.waitForTimeout(1000);
  assert.ok(await alpha() > early + 0.2, 'Content must reveal further with additional scrolling');
  await page.screenshot({ path: 'artifacts/treatment-fluid-middle.png' });
  await page.evaluate(() => window.scrollTo({ top: 3600, behavior: 'instant' }));
  await page.waitForTimeout(1000);
  assert.ok(await alpha() > 0.99);
  assert.ok(Number(await page.locator('.treatment-summary').evaluate(el => getComputedStyle(el).opacity)) > 0.99);
  const lastStep = () => page.locator('.care-steps li').last().evaluate(el => Number(getComputedStyle(el).opacity));
  assert.ok(await lastStep() > 0 && await lastStep() < 0.99, 'Slower entrance must continue visibly during the short hold');
  await page.evaluate(() => window.scrollTo({ top: 3750, behavior: 'instant' }));
  await page.waitForTimeout(1000);
  assert.ok(await lastStep() > 0.99, 'All steps must finish before the section releases');
  await page.screenshot({ path: 'artifacts/treatment-fluid-complete.png' });
  await page.mouse.wheel(0, 430);
  await page.waitForTimeout(1100);
  assert.ok(await page.evaluate(() => scrollY > 3900), 'Wheel must remain native after arrival');
  await page.evaluate(() => window.scrollTo({ top: 3150, behavior: 'instant' }));
  await page.waitForTimeout(1000);
  assert.ok(Math.abs(await alpha() - early) < 0.02, 'Reverse scrolling must reverse content animation');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.evaluate(() => window.scrollTo({ top: 2500, behavior: 'instant' }));
  await page.mouse.wheel(0, 120);
  await page.waitForTimeout(500);
  assert.ok(await page.evaluate(() => scrollY < 2800), 'Reduced motion must keep native scrolling');
  assert.equal(await page.locator('.treatment-intro').evaluate(el => getComputedStyle(el).visibility), 'visible');
  assert.deepEqual(errors, []);
  console.log('PASS: native wheel, progressive reveal, title/card order, idle stability, reverse scrub, complete framing and reduced motion.');
} finally { await browser.close(); }
