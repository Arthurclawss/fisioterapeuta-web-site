import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';

await mkdir('artifacts', { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const errors = [];
try {
  const desktop = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  desktop.on('pageerror', error => errors.push(error.message));
  const response = await desktop.goto('http://localhost:3000', { waitUntil: 'networkidle' });
  assert.equal(response.status(), 200);
  await desktop.waitForTimeout(1800);
  await desktop.screenshot({ path: 'artifacts/hero-desktop.png' });
  assert.equal(await desktop.locator('h1').innerText(), 'Seu corpo.\nSeu movimento.\nSua liberdade.');
  assert.equal(await desktop.locator('.pin-spacer').count(), 4);
  const before = await desktop.locator('.portrait-scroll').evaluate(el => el.getBoundingClientRect().left);
  await desktop.evaluate(() => window.scrollTo({ top: 600, behavior: 'instant' }));
  await desktop.waitForTimeout(1500);
  const after = await desktop.locator('.portrait-scroll').evaluate(el => el.getBoundingClientRect().left);
  assert.ok(after < before - 100, 'Portrait must move left with scroll');
  assert.equal(await desktop.locator('.help-panel').evaluate(el => getComputedStyle(el).visibility), 'hidden', 'Help must wait until portrait finishes');
  await desktop.screenshot({ path: 'artifacts/hero-scroll.png' });
  await desktop.evaluate(() => window.scrollTo({ top: 1150, behavior: 'instant' }));
  await desktop.waitForTimeout(1800);
  const finalPhotoX = await desktop.locator('.portrait-scroll').evaluate(el => el.getBoundingClientRect().left);
  assert.ok(finalPhotoX < 60, 'Portrait must settle on left');
  assert.ok(Number(await desktop.locator('.help-panel h2').evaluate(el => getComputedStyle(el).opacity)) > 0.95);
  await desktop.screenshot({ path: 'artifacts/help-desktop.png' });
  await desktop.evaluate(() => window.scrollTo({ top: 1450, behavior: 'instant' }));
  await desktop.waitForTimeout(1400);
  assert.ok(Math.abs(finalPhotoX - await desktop.locator('.portrait-scroll').evaluate(el => el.getBoundingClientRect().left)) < 2, 'Portrait must stay still during text reveal');
  await desktop.evaluate(() => window.scrollTo({ top: 2500, behavior: 'instant' }));
  await desktop.waitForTimeout(1600);
  assert.equal(await desktop.locator('.help-panel').evaluate(el => getComputedStyle(el).visibility), 'hidden');
  assert.ok(Number(await desktop.locator('.about-panel h2').evaluate(el => getComputedStyle(el).opacity)) > 0.95);
  assert.ok(Math.abs(finalPhotoX - await desktop.locator('.portrait-scroll').evaluate(el => el.getBoundingClientRect().left)) < 2, 'Portrait must remain in same position for about section');
  await desktop.screenshot({ path: 'artifacts/about-desktop.png' });
  const backdropTop = await desktop.locator('.portrait-scroll').evaluate(el => el.getBoundingClientRect().top);
  await desktop.evaluate(() => window.scrollTo({ top: 3150, behavior: 'instant' }));
  await desktop.waitForTimeout(1600);
  const overlayTop = await desktop.locator('#tratamentos').evaluate(el => el.getBoundingClientRect().top);
  assert.ok(overlayTop > 400 && overlayTop < 500, 'Treatment section must cover half the scene during entry');
  assert.ok(Math.abs(backdropTop - await desktop.locator('.portrait-scroll').evaluate(el => el.getBoundingClientRect().top)) < 2, 'Previous scene must stay pinned behind overlay');
  assert.ok(await desktop.evaluate(() => !!document.elementFromPoint(720, 700)?.closest('#tratamentos')), 'Treatment must paint in front of the previous scene');
  await desktop.screenshot({ path: 'artifacts/treatments-overlay.png' });
  await desktop.evaluate(() => window.scrollTo({ top: 3600, behavior: 'instant' }));
  await desktop.waitForTimeout(1500);
  assert.ok(Math.abs(await desktop.locator('#tratamentos').evaluate(el => el.getBoundingClientRect().top)) < 2, 'Treatment must reach top at end of transition');
  await desktop.screenshot({ path: 'artifacts/treatments-covered.png' });
  const titleTop = await desktop.locator('#treatment-title').evaluate(el => el.getBoundingClientRect().top);
  await desktop.evaluate(() => window.scrollTo({ top: 3800, behavior: 'instant' }));
  await desktop.waitForTimeout(1200);
  assert.ok(Math.abs(await desktop.locator('#tratamentos').evaluate(el => el.getBoundingClientRect().top)) < 2, 'Treatment must hold framing briefly at top');
  assert.ok(Math.abs(titleTop - await desktop.locator('#treatment-title').evaluate(el => el.getBoundingClientRect().top)) < 2, 'Treatment content must remain still during hold');
  await desktop.screenshot({ path: 'artifacts/treatments-hold.png' });
  await desktop.evaluate(() => window.scrollTo({ top: 4100, behavior: 'instant' }));
  await desktop.waitForTimeout(1200);
  assert.ok(await desktop.locator('#tratamentos').evaluate(el => el.getBoundingClientRect().top < -100), 'Treatment must release after short hold');
  await desktop.evaluate(() => window.scrollTo({ top: 2500, behavior: 'instant' }));
  await desktop.waitForTimeout(1500);
  assert.ok(await desktop.locator('#tratamentos').evaluate(el => el.getBoundingClientRect().top > innerHeight), 'Reversing scroll must uncover previous section');
  await desktop.locator('.about-panel .text-link').click();
  await desktop.waitForTimeout(2000);
  assert.equal(new URL(desktop.url()).hash, '#tratamentos');
  assert.ok(await desktop.locator('#tratamentos').evaluate(el => el.getBoundingClientRect().top < innerHeight));
  assert.equal(await desktop.locator('.treatment-feature').count(), 3);
  await desktop.screenshot({ path: 'artifacts/treatments-desktop.png' });
  await desktop.locator('.treatment-intro .treatment-button').click();
  await desktop.waitForTimeout(1400);
  assert.equal(new URL(desktop.url()).hash, '#contato');
  await desktop.evaluate(() => window.scrollTo({ top: 1150, behavior: 'instant' }));
  await desktop.waitForTimeout(1500);
  assert.ok(Number(await desktop.locator('.help-panel h2').evaluate(el => getComputedStyle(el).opacity)) > 0.95);
  assert.equal(await desktop.locator('.about-panel').evaluate(el => getComputedStyle(el).visibility), 'hidden');
  await desktop.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
  await desktop.waitForTimeout(1500);
  assert.ok(Number(await desktop.locator('.hero-copy').evaluate(el => getComputedStyle(el).opacity)) > 0.95);
  await desktop.locator('.hero-actions .text-link').click();
  await desktop.waitForTimeout(1800);
  assert.ok(Number(await desktop.locator('.help-panel h2').evaluate(el => getComputedStyle(el).opacity)) > 0.95, 'Help navigation must land on help, not about');
  await desktop.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
  await desktop.waitForTimeout(1400);
  await desktop.locator('.hero-actions .primary-button').click();
  await desktop.waitForTimeout(1500);
  assert.equal(new URL(desktop.url()).hash, '#contato');
  assert.ok(await desktop.locator('#contato').evaluate(el => el.getBoundingClientRect().top < innerHeight));

  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  mobile.on('pageerror', error => errors.push(error.message));
  await mobile.goto('http://localhost:3000', { waitUntil: 'networkidle' });
  await mobile.waitForTimeout(1800);
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.equal(await mobile.locator('.pin-spacer').count(), 0);
  await mobile.screenshot({ path: 'artifacts/hero-mobile.png' });
  await mobile.getByRole('button', { name: 'Abrir menu' }).click();
  await mobile.locator('#mobile-menu').getByRole('link', { name: 'Como posso te ajudar' }).click();
  await mobile.waitForTimeout(600);
  assert.equal(await mobile.locator('#mobile-menu').count(), 0);
  assert.equal(new URL(mobile.url()).hash, '#cuidado');
  await mobile.waitForTimeout(1200);
  assert.ok(Number(await mobile.locator('.help-panel h2').evaluate(el => getComputedStyle(el).opacity)) > 0.95);
  await mobile.screenshot({ path: 'artifacts/care-mobile.png' });
  await mobile.locator('#sobre').scrollIntoViewIfNeeded();
  await mobile.waitForTimeout(1600);
  assert.ok(Number(await mobile.locator('.about-panel h2').evaluate(el => getComputedStyle(el).opacity)) > 0.95);
  await mobile.screenshot({ path: 'artifacts/about-mobile.png' });
  await mobile.locator('.about-panel .text-link').click();
  await mobile.waitForTimeout(1800);
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.ok(Number(await mobile.locator('.treatment-intro').evaluate(el => getComputedStyle(el).opacity)) > 0.95);
  await mobile.screenshot({ path: 'artifacts/treatments-mobile.png' });

  const reduced = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
  await reduced.goto('http://localhost:3000', { waitUntil: 'networkidle' });
  assert.equal(await reduced.locator('.pin-spacer').count(), 0);
  assert.equal(await reduced.locator('.title-line').first().evaluate(el => getComputedStyle(el).opacity), '1');
  assert.equal(await reduced.locator('.about-panel').evaluate(el => getComputedStyle(el).visibility), 'visible');
  assert.equal(await reduced.locator('.treatment-intro').evaluate(el => getComputedStyle(el).visibility), 'visible');
  assert.deepEqual(errors, []);
  console.log('PASS: desktop, help/about sequence, stationary portrait, reverse scroll, chapter navigation, CTA, mobile, reduced motion, no runtime errors.');
} finally { await browser.close(); }
