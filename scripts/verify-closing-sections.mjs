import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';

const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://localhost:3000', { waitUntil: 'networkidle' });
  await page.locator('#depoimentos').scrollIntoViewIfNeeded();
  await page.waitForTimeout(1500);
  assert.equal(await page.locator('.demo-label').innerText(), 'DEPOIMENTOS ILUSTRATIVOS');
  assert.match(await page.locator('.testimonial-person').innerText(), /fictício/);
  const firstQuote = await page.locator('blockquote').innerText();
  await page.getByRole('button', { name: 'Próximo depoimento' }).click();
  await page.waitForTimeout(600);
  assert.notEqual(await page.locator('blockquote').innerText(), firstQuote);
  await page.getByRole('button', { name: 'Depoimento anterior' }).click();
  await page.waitForTimeout(600);
  assert.equal(await page.locator('blockquote').innerText(), firstQuote);
  const payment = page.getByRole('button', { name: /Quais são as formas de pagamento/ });
  await payment.click();
  await page.waitForTimeout(600);
  assert.equal(await payment.getAttribute('aria-expanded'), 'true');
  assert.ok(await page.locator('#faq-answer-2').isVisible());
  await payment.click();
  await page.waitForTimeout(600);
  assert.equal(await page.locator('#faq-answer-2').count(), 0);
  const bounds = await page.locator('.patient-stage').evaluate(el => ({ top: el.getBoundingClientRect().top + scrollY, height: el.offsetHeight }));
  await page.evaluate(top => window.scrollTo({ top, behavior: 'instant' }), bounds.top);
  await page.waitForTimeout(1200);
  const heldTop = await page.locator('.patient-section').evaluate(el => el.getBoundingClientRect().top);
  await page.evaluate(top => window.scrollTo({ top, behavior: 'instant' }), bounds.top + 100);
  await page.waitForTimeout(500);
  assert.ok(Math.abs(heldTop) < 3 && Math.abs(await page.locator('.patient-section').evaluate(el => el.getBoundingClientRect().top)) < 3, 'Section 5 must pause briefly at the top');
  assert.equal(await page.locator('.faq-item h3>button').first().evaluate(el => getComputedStyle(el).fontSize), '16px');
  assert.equal(await page.locator('.patient-intro').evaluate(el => getComputedStyle(el).color), 'rgb(209, 225, 231)');
  await page.screenshot({ path: 'artifacts/patients-faq-desktop.png' });
  const revealStart = bounds.top + bounds.height - 900;
  const watermarkWidth = await page.locator('.closing-watermark').evaluate(el => el.getBoundingClientRect().width);
  for (const progress of [0.1, 0.5, 0.9]) {
    await page.evaluate(top => window.scrollTo({ top, behavior: 'instant' }), revealStart + 900 * progress);
    await page.waitForTimeout(400);
    const background = await page.locator('.closing-backdrop').evaluate(el => {
      const rect = el.getBoundingClientRect();
      const scene = el.parentElement.getBoundingClientRect();
      return { transform: getComputedStyle(el).transform, topGap: rect.top - scene.top, bottomGap: scene.bottom - rect.bottom };
    });
    assert.equal(background.transform, 'none', 'Contact background must keep its final scale throughout reveal');
    assert.ok(Math.abs(background.topGap) < 1 && Math.abs(background.bottomGap) < 1, 'Background must cover the entire scene without dark gaps');
    assert.ok(Math.abs(await page.locator('.closing-watermark').evaluate(el => el.getBoundingClientRect().width) - watermarkWidth) < 1, 'Logo must retain its size throughout reveal');
  }
  await page.evaluate(top => window.scrollTo({ top, behavior: 'instant' }), revealStart + 450);
  await page.waitForTimeout(1200);
  const sceneTop = await page.locator('.closing-scene').evaluate(el => el.getBoundingClientRect().top);
  assert.ok(Math.abs(sceneTop) < 3, `Contact must stay still behind curtain, top=${sceneTop}`);
  const curtainBottom = await page.locator('.patient-section').evaluate(el => el.getBoundingClientRect().bottom);
  assert.ok(curtainBottom > 440 && curtainBottom < 460);
  assert.ok(await page.evaluate(() => !!document.elementFromPoint(720, 160)?.closest('.patient-section')), 'Section 5 must remain in front at upper half');
  assert.ok(await page.evaluate(() => !!document.elementFromPoint(720, 750)?.closest('.closing-scene')), 'Section 6 must be revealed underneath at lower half');
  await page.screenshot({ path: 'artifacts/closing-inverse-parallax.png' });
  await page.evaluate(top => window.scrollTo({ top, behavior: 'instant' }), bounds.top + bounds.height);
  await page.waitForTimeout(1200);
  assert.ok(Math.abs(await page.locator('.closing-scene').evaluate(el => el.getBoundingClientRect().top)) < 3);
  await page.screenshot({ path: 'artifacts/contact-footer-desktop.png' });
  assert.match(await page.locator('address').innerText(), /Walter Duarte Pereira, 1620/);
  assert.match(await page.locator('.footer-instagram').getAttribute('href'), /instagram.com\/dr.rudymollick/);
  assert.equal(await page.locator('a[href^="https://wa.me"]').count(), 0, 'Fictitious number must never route to a real recipient');
  await page.getByRole('button', { name: 'Conversar pelo WhatsApp' }).click();
  assert.ok(await page.locator('dialog').evaluate(el => el.open));
  assert.match(await page.locator('dialog').innerText(), /demonstrativo/);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('dialog').evaluate(el => el.open), false);
  await page.route('https://maps.google.com/**', route => route.fulfill({ contentType: 'text/html', body: '<html><body>Embedded map test</body></html>' }));
  await page.getByRole('button', { name: 'Carregar mapa do Google' }).click();
  assert.match(decodeURIComponent(await page.locator('.map-frame iframe').getAttribute('src')), /Rua Walter Duarte Pereira, 1620/);
  await page.getByRole('link', { name: 'Política de privacidade' }).click();
  await page.waitForURL('**/privacidade');
  assert.match(await page.locator('h1').innerText(), /privacidade/);
  assert.ok(await page.getByRole('heading', { name: 'Depoimentos', exact: true }).isVisible());
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    await page.goto('http://localhost:3000', { waitUntil: 'networkidle' });
    assert.equal(await page.locator('.pin-spacer').count(), 0);
    await page.locator('#depoimentos').scrollIntoViewIfNeeded();
    await page.waitForTimeout(600);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `No overflow at ${width}px`);
    if (width === 390) await page.screenshot({ path: 'artifacts/patients-mobile.png' });
    await page.locator('.patient-bottom a').click();
    await page.waitForTimeout(1200);
    assert.equal(new URL(page.url()).hash, '#contato');
    assert.ok(await page.locator('#contato').evaluate(el => el.getBoundingClientRect().top < innerHeight));
    if (width === 390) await page.screenshot({ path: 'artifacts/contact-mobile.png' });
  }
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('http://localhost:3000', { waitUntil: 'networkidle' });
  assert.equal(await page.locator('.pin-spacer').count(), 0);
  assert.equal(await page.locator('.closing-shell').evaluate(el => getComputedStyle(el).marginTop), '0px');
  assert.deepEqual(errors, []);
  console.log('PASS: illustrative testimonials, carousel, FAQ, inverse curtain and layer order, contact navigation, demo WhatsApp, map integration, privacy, mobile and reduced motion.');
} finally { await browser.close(); }
