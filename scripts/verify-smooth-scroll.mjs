import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';

const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://localhost:3000', { waitUntil: 'networkidle' });
  assert.ok(await page.locator('html').evaluate(el => el.classList.contains('lenis')));
  await page.waitForTimeout(1300);
  await page.mouse.move(720, 450);
  await page.mouse.wheel(0, 700);
  await page.waitForTimeout(90);
  const early = await page.evaluate(() => scrollY);
  await page.waitForTimeout(140);
  const middle = await page.evaluate(() => scrollY);
  await page.waitForTimeout(1200);
  const final = await page.evaluate(() => scrollY);
  assert.ok(early > 0 && early < middle && middle < final, 'Wheel motion must spread smoothly across frames');
  assert.ok(Math.abs(final - 700) < 3, `Wheel must settle at intended position, got ${final}`);
  await page.getByRole('link', { name: 'Voltar ao início ↑', exact: true }).evaluate(el => el.click());
  await page.waitForTimeout(1250);
  assert.ok(await page.evaluate(() => scrollY < 3), 'Global anchor must return smoothly to top');
  await page.locator('.hero-actions .text-link').click();
  await page.waitForTimeout(1500);
  assert.equal(new URL(page.url()).hash, '#cuidado');
  assert.ok(Number(await page.locator('.help-panel h2').evaluate(el => getComputedStyle(el).opacity)) > 0.99);
  await page.locator('.help-panel .text-link').click();
  await page.waitForTimeout(1500);
  assert.equal(new URL(page.url()).hash, '#contato');
  assert.ok(Math.abs(await page.locator('.closing-scene').evaluate(el => el.getBoundingClientRect().top)) < 3);
  await page.getByRole('button', { name: 'Conversar pelo WhatsApp' }).click();
  const beforeModalWheel = await page.evaluate(() => scrollY);
  await page.mouse.wheel(0, 300);
  await page.waitForTimeout(500);
  assert.ok(Math.abs(await page.evaluate(() => scrollY) - beforeModalWheel) < 3, 'Dialog must not scroll the background');
  await page.keyboard.press('Escape');
  await page.waitForTimeout(100);
  await page.getByRole('link', { name: 'Política de privacidade' }).click();
  await page.waitForURL('**/privacidade');
  await page.waitForTimeout(400);
  assert.ok(await page.locator('html').evaluate(el => el.classList.contains('lenis')), 'Smooth scrolling must work on privacy page too');
  await page.getByRole('link', { name: 'Voltar ao site' }).click();
  await page.waitForURL('http://localhost:3000/');
  await page.waitForTimeout(700);
  assert.equal(await page.locator('.pin-spacer').count(), 4, 'Route return must not duplicate pinning');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.waitForTimeout(150);
  assert.equal(await page.locator('html').evaluate(el => el.classList.contains('lenis')), false);
  assert.equal(await page.locator('.pin-spacer').count(), 0);
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.waitForTimeout(250);
  assert.equal(await page.locator('.pin-spacer').count(), 4);
  assert.deepEqual(errors, []);
  console.log('PASS: global smooth wheel, anchors, pinned scene navigation, modal scroll isolation, route lifecycle and reduced motion.');
} finally { await browser.close(); }
